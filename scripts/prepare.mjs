#!/usr/bin/env node
/* Generates the runtime assets the page needs:
   - src/fonts.css  (fonts inlined as data URIs so file:// has no CORS issues)
   - src/data/timeline.js  (window.TL = <timeline.json>)
*/
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const FONTS = path.join(ROOT, 'assets', 'fonts');

const faces = [
  ['BengaliUI', 'NotoSansBengali-Regular.ttf', 400],
  ['BengaliUI', 'NotoSansBengali-Medium.ttf', 500],
  ['BengaliUI', 'NotoSansBengali-SemiBold.ttf', 600],
  ['BengaliUI', 'NotoSansBengali-Bold.ttf', 700],
  ['BengaliUI', 'NotoSansBengali-SemiBold.ttf', 800],
  ['BengaliUI', 'NotoSansBengali-Regular.ttf', 300],
  ['BengaliDisplay', 'BalooDa2-Bold.ttf', 700],
  ['BengaliDisplay', 'BalooDa2-ExtraBold.ttf', 800],
  ['BengaliDisplay', 'BalooDa2-Bold.ttf', 600],
  ['HindUI', 'HindSiliguri-Regular.ttf', 400],
  ['HindUI', 'HindSiliguri-SemiBold.ttf', 600],
  ['HindUI', 'HindSiliguri-Bold.ttf', 700],
  ['HindUI', 'HindSiliguri-SemiBold.ttf', 500],
  ['Geo', 'Poppins-Regular.ttf', 400],
  ['Geo', 'Poppins-Medium.ttf', 500],
  ['Geo', 'Poppins-SemiBold.ttf', 600],
  ['Geo', 'Poppins-Bold.ttf', 700],
  ['Geo', 'Poppins-ExtraBold.ttf', 800],
  ['Geo', 'Poppins-Black.ttf', 900],
];

let css = '/* generated by scripts/prepare.mjs — do not edit */\n';
for (const [fam, file, weight] of faces) {
  const b64 = fs.readFileSync(path.join(FONTS, file)).toString('base64');
  css += `@font-face{font-family:'${fam}';font-style:normal;font-weight:${weight};font-display:block;` +
    `src:url(data:font/ttf;base64,${b64}) format('truetype');}\n`;
}
fs.writeFileSync(path.join(ROOT, 'src', 'fonts.css'), css);
console.log('fonts.css', (css.length / 1024 / 1024).toFixed(2), 'MB');

const tl = fs.readFileSync(path.join(ROOT, 'data', 'timeline.json'), 'utf8');
fs.mkdirSync(path.join(ROOT, 'src', 'data'), { recursive: true });
fs.writeFileSync(path.join(ROOT, 'src', 'data', 'timeline.js'), `window.TL = ${tl};\n`);
console.log('timeline.js ok');
