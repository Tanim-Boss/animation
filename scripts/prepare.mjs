#!/usr/bin/env node
/* Inline the Bengali/Latin font files and embed the project + measured cue data
 * for local-file Chromium rendering. */
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const fontDir = path.join(ROOT, 'assets', 'fonts');
const faces = [
  ['NotoBengali', 'NotoSansBengali-Regular.ttf', 400],
  ['NotoBengali', 'NotoSansBengali-Medium.ttf', 500],
  ['NotoBengali', 'NotoSansBengali-SemiBold.ttf', 600],
  ['NotoBengali', 'NotoSansBengali-Bold.ttf', 700],
  ['Hind', 'HindSiliguri-Regular.ttf', 400],
  ['Hind', 'HindSiliguri-SemiBold.ttf', 600],
  ['Hind', 'HindSiliguri-Bold.ttf', 700],
  ['Baloo', 'BalooDa2-Bold.ttf', 700],
  ['Baloo', 'BalooDa2-ExtraBold.ttf', 800],
  ['Poppins', 'Poppins-Regular.ttf', 400],
  ['Poppins', 'Poppins-Medium.ttf', 500],
  ['Poppins', 'Poppins-SemiBold.ttf', 600],
  ['Poppins', 'Poppins-Bold.ttf', 700],
  ['Poppins', 'Poppins-ExtraBold.ttf', 800],
];

let css = '/* generated by scripts/prepare.mjs — do not edit */\n';
for (const [family, filename, weight] of faces) {
  const bytes = fs.readFileSync(path.join(fontDir, filename));
  const base64 = bytes.toString('base64');
  css += `@font-face{font-family:'${family}';font-style:normal;font-weight:${weight};font-display:block;` +
    `src:url(data:font/ttf;base64,${base64}) format('truetype');}\n`;
}
fs.writeFileSync(path.join(ROOT, 'src', 'fonts.css'), css);

const timeline = JSON.parse(fs.readFileSync(path.join(ROOT, 'data', 'timeline.json'), 'utf8'));
const project = JSON.parse(fs.readFileSync(path.join(ROOT, 'data', 'project.json'), 'utf8'));
const dataDir = path.join(ROOT, 'src', 'data');
fs.mkdirSync(dataDir, { recursive: true });
fs.writeFileSync(path.join(dataDir, 'timeline.js'), `window.TL = ${JSON.stringify(timeline)};\n`);
fs.writeFileSync(path.join(dataDir, 'project.js'), `window.PROJECT = ${JSON.stringify(project)};\n`);
console.log(`prepared ${faces.length} fonts, ${timeline.cues.reduce((n, c) => n + c.words.length, 0)} timed words`);
